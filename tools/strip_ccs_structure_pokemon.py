#!/usr/bin/env python3
"""Takes the Pokémon out of Cobblemon Cities & Structures' buildings (asked for on 2026-11-26).

Six CCS gym templates (Pewter, Viridian, Vermilion, Celadon, Fuchsia, Cinnabar) were saved with live Pokémon in
them: the builder's level 10 Bulbasaur in each, and a perfect-IV Varoom (14), Ampharos (34), Electrode (46), Iron
Valiant (66), Walking Wake (73) and Archaludon (77). Every new gym placed them in the world as wild Pokémon, free to
catch, and Spawn Notification announced the Paradox ones as "max IV" spawns that players then couldn't find.

This copies every CCS structure that holds a `cobblemon:pokemon` entity into kubejs/data/ccs/structure/ with those
entities cut out of its `entities` list (the rest of the file byte for byte), and writes the Pokémon's UUIDs (the
same in every copy of a template) to kubejs/server_scripts/campfiremons/ccs_built_in_pokemon.js, which stops them
joining the world from gyms generated before this fix. Re-run after updating CCS.
    python3 tools/strip_ccs_structure_pokemon.py
"""
import glob
import gzip
import struct
import sys
import uuid
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / 'quest_book'))
from snbt import mods_dir  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'kubejs' / 'data' / 'ccs' / 'structure'
SCRIPT = ROOT / 'kubejs' / 'server_scripts' / 'campfiremons' / 'ccs_built_in_pokemon.js'


def parse(b, p, t):
    """(value, end offset) of a tag payload of type t at p"""
    if t in (1, 2, 3, 4, 5, 6):
        f, n = {1: ('>b', 1), 2: ('>h', 2), 3: ('>i', 4), 4: ('>q', 8), 5: ('>f', 4), 6: ('>d', 8)}[t]
        return struct.unpack_from(f, b, p)[0], p + n
    if t == 7:
        n = struct.unpack_from('>i', b, p)[0]; return b[p+4:p+4+n], p + 4 + n
    if t == 8:
        n = struct.unpack_from('>H', b, p)[0]; return b[p+2:p+2+n].decode('utf8'), p + 2 + n
    if t == 9:
        et, n = b[p], struct.unpack_from('>i', b, p + 1)[0]; p += 5; out = []
        for _ in range(n):
            v, p = parse(b, p, et); out.append(v)
        return out, p
    if t == 10:
        o = {}
        while True:
            tt = b[p]; p += 1
            if tt == 0: return o, p
            k, p = parse(b, p, 8); o[k], p = parse(b, p, tt)
    if t == 11:
        n = struct.unpack_from('>i', b, p)[0]; return list(struct.unpack_from('>%di' % n, b, p + 4)), p + 4 + 4*n
    if t == 12:
        n = struct.unpack_from('>i', b, p)[0]; return None, p + 4 + 8*n
    raise ValueError(t)


def strip(raw):
    """(new file bytes, [(species, uuid)]) with the cobblemon:pokemon entities removed, or (None, []) if there are none"""
    b = gzip.decompress(raw)
    assert b[0] == 10
    p = 3 + struct.unpack_from('>H', b, 1)[0]  # root compound payload
    while b[p] != 0:
        tt = b[p]; name, q = parse(b, p + 1, 8)
        if name == 'entities' and tt == 9:
            if struct.unpack_from('>i', b, q + 1)[0] == 0: return None, []  # empty (stored with element type 0)
            assert b[q] == 10, 'entities is not a list of compounds'
            count_at, p0 = q + 1, q + 5
            keep, gone, p = [], [], p0
            for _ in range(struct.unpack_from('>i', b, count_at)[0]):
                e, end = parse(b, p, 10)
                n = e.get('nbt', {})
                if n.get('id') == 'cobblemon:pokemon':
                    u = struct.pack('>4i', *n['Pokemon']['UUID'])
                    gone.append((n['Pokemon'].get('Species'), str(uuid.UUID(bytes=u))))
                else:
                    keep.append(b[p:end])
                p = end
            if not gone: return None, []
            nb = b[:count_at] + struct.pack('>i', len(keep)) + b''.join(keep) + b[p:]
            return gzip.compress(nb, mtime=0), gone
        _, p = parse(b, q, tt)
    return None, []


def main():
    jar = glob.glob(mods_dir() + '/Cobblemon Cities*.jar')
    if len(jar) != 1: raise SystemExit(f'expected one Cobblemon Cities & Structures jar, found {jar}')
    z = zipfile.ZipFile(jar[0])
    found = {}
    for n in sorted(z.namelist()):
        if not (n.startswith('data/ccs/structure/') and n.endswith('.nbt')): continue
        new, gone = strip(z.read(n))
        if not new: continue
        out = OUT / n[len('data/ccs/structure/'):]
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(new)
        print(f'{n[len("data/ccs/structure/"):]}: removed', ', '.join(s.replace('cobblemon:', '') for s, _ in gone))
        for s, u in gone: found.setdefault(u, s)
    ids = '\n'.join(f"  '{u}', // {s.replace('cobblemon:', '')}" for u, s in sorted(found.items(), key=lambda x: x[1]))
    SCRIPT.write_text(f"""// Generated by tools/strip_ccs_structure_pokemon.py; don't edit by hand.
// Cobblemon Cities & Structures' gym templates were saved with live Pokémon in them (perfect-IV aces up to level 77, and
// Paradox Pokémon that Spawn Notification announced as wild spawns). kubejs/data/ccs/structure/ now has them cut out;
// this stops the copies already in gyms generated before that from joining the world when their chunk loads. Every copy
// of a template's Pokémon has the template's UUID, so nothing else can match.

const CCS_BUILT_IN_POKEMON = [
{ids}
]

EntityEvents.spawned('cobblemon:pokemon', event => {{
  let pokemon = event.entity.getPokemon()
  if (!pokemon || CCS_BUILT_IN_POKEMON.indexOf(String(pokemon.getUuid())) < 0) return
  console.info(`[campfiremons] removed a built-in CCS ${{pokemon.getSpecies().getName()}} at ${{Math.round(event.entity.x)}} ${{Math.round(event.entity.y)}} ${{Math.round(event.entity.z)}}`)
  event.cancel()
}})
""")
    print(f'{len(found)} Pokémon UUIDs in {SCRIPT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
