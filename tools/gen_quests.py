# ---- SNBT output ----------------------------------------------------------------------------------------------------

def snbt(v, indent=0):
    tab = "\t" * indent
    if isinstance(v, tuple) and v[0] == "long":
        return f"{v[1]}L"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v}d"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        if not v:
            return "[ ]"
        inner = "\n".join(f"{tab}\t{snbt(x, indent + 1)}" for x in v)
        return f"[\n{inner}\n{tab}]"
    if isinstance(v, dict):
        inner = "\n".join(f"{tab}\t{k}: {snbt(v[k], indent + 1)}" for k in sorted(v))
        return f"{{\n{inner}\n{tab}}}"
    raise TypeError(v)


def write(rel, obj):
    p = QUESTS / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(snbt(obj) + "\n")


def main():
    if (QUESTS / "data.snbt").exists() and "--force" not in sys.argv:
        sys.exit(f"{QUESTS} already has a quest book (edited in game?). Re-run with --force to overwrite it.")
    shutil.rmtree(QUESTS, ignore_errors=True)

    write("data.snbt", {
        "default_autoclaim_rewards": "disabled", "default_consume_items": False, "default_quest_disable_jei": False,
        "default_quest_shape": "circle", "default_reward_team": False, "detection_delay": 20, "disable_gui": False,
        "drop_book_on_death": False, "drop_loot_crates": False, "emergency_items_cooldown": 300,
        "fallback_locale": "", "grid_scale": 0.5, "hide_excluded_quests": False,
        "icon": {"id": "minecraft:campfire"}, "lock_message": "", "pause_game": False,
        "progression_mode": "flexible", "show_lock_icons": True, "verify_on_load": False, "version": 13,
    })
    write("chapter_groups.snbt", {"chapter_groups": []})
    write("lang/en_us/file.snbt", {"file.0000000000000001.title": "Campfiremons"})
    chapter_titles = {}
    for n in range(10):
        cid = qid("chapter", n)
        name = f"stage_{n}"
        chapter_titles[f"chapter.{cid}.title"] = "Campfire Start" if n == 0 else (
            f"Stage {n}: {BADGES[n]} Badge" if n < 9 else "Stage 9: Champion")
        quests, lang = [], {}
        for key, icon, title, sub, desc, tasks, rewards, shape, x, y, deps in chapter(n):
            this = qid(f"s{n}", key)
            quests.append({
                "dependencies": [qid(f"s{n}", d) for d in deps], "icon": {"id": icon}, "id": this,
                "rewards": rewards, "shape": shape, "size": 1.5 if shape in ("hexagon", "gear") else 1.0,
                "tasks": tasks, "x": float(x), "y": float(y),
            })
            lang[f"quest.{this}.title"] = title
            lang[f"quest.{this}.quest_subtitle"] = sub
            lang[f"quest.{this}.quest_desc"] = desc
        if n > 0:  # each chapter opens from the previous chapter's gym capstone
            quests[0]["dependencies"].append(qid(f"s{n - 1}", "gym"))
        write(f"chapters/{name}.snbt", {
            "default_hide_dependency_lines": False, "default_quest_shape": "", "filename": name, "group": "",
            "icon": {"id": "cobblemon:" + (gen_finds.STAGE_ICONS[n - 1] if n else "poke_ball")}, "id": cid,
            "order_index": n, "quest_links": [], "quests": quests,
        })
        write(f"lang/en_us/chapters/{name}.snbt", lang)
    write("lang/en_us/chapter.snbt", chapter_titles)
    print(f"wrote 10 chapters to {QUESTS.relative_to(QUESTS.parents[2])}")


if __name__ == "__main__":
    main()
