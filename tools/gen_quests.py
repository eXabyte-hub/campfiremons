# ---- reward kits: generous, but only items usable at that stage ----------------------------------------------------

def kit(n):
    ball = "poke_ball" if n == 0 else "great_ball" if n < 3 else "ultra_ball"
    potion = ["potion", "potion", "super_potion", "super_potion", "hyper_potion", "hyper_potion", "max_potion",
              "max_potion", "full_restore", "full_restore"][n]
    candy = ["exp_candy_xs", "exp_candy_s", "exp_candy_m", "exp_candy_m", "exp_candy_l", "exp_candy_l",
             "exp_candy_xl", "exp_candy_xl", "exp_candy_xl", "exp_candy_xl"][n]
    revive = None if n < 2 else "revive" if n < 6 else "max_revive"
    return {k: f"cobblemon:{v}" for k, v in dict(ball=ball, potion=potion, candy=candy, revive=revive).items() if v}


def qid(*parts):
    """Stable 16-hex FTB Quests id from a name (so --force regenerates the same ids)."""
    return hashlib.sha1("/".join(map(str, parts)).encode()).hexdigest()[:16].upper()


def rewards(key, xp_levels, *items):
    out = [{"id": qid(key, "xp"), "type": "xp_levels", "xp_levels": xp_levels}]
    out += [{"count": count, "id": qid(key, "reward", i), "item": {"count": 1, "id": item}, "type": "item"}
            for i, (item, count) in enumerate(items) if item and count]
    return out


# ---- tasks ----------------------------------------------------------------------------------------------------------

def adv_task(key, advancement):
    return {"advancement": advancement, "criterion": "", "id": qid(key, "task"), "type": "advancement"}


def check_task(key):
    return {"id": qid(key, "task"), "type": "checkmark"}


def mon_task(key, action, amount, form="", shiny=False):
    return {
        "action": action, "amount": ("long", amount), "biome": "", "dimension": "", "form": form, "gender": "",
        "id": qid(key, "task"), "poke_ball_used": "", "pokemon": "", "pokemon_type": "", "region": "",
        "shiny": shiny, "time_max": ("long", 24000), "time_min": ("long", 0),
        "type": "cobblemon_tasks:cobblemon_task",
    }


# ---- key fights between gyms (RCT series graph) ---------------------------------------------------------------------

def key_fights(jar_path):
    """{stage: ["Rocket Admin Archer (Lv21)", ...]} = key trainers you meet after this stage's gym, before the next."""
    z = zipfile.ZipFile(jar_path)
    names = set(z.namelist())
    mobs = {n.rsplit("/", 1)[1][:-5]: json.loads(z.read(n)) for n in names
            if n.startswith("data/rctmod/mobs/trainers/single/") and n.endswith(".json")}
    keys = {t: m for t, m in mobs.items() if SERIES in m.get("series", []) and not m.get("optional", False)}

    def reqs(m):
        r = m.get("requiredDefeats", [])
        r = r.get(SERIES, []) if isinstance(r, dict) else r
        return {x for g in r for x in (g if isinstance(g, list) else [g])}

    depth = {}

    def d(t):
        if t not in depth:
            depth[t] = 0
            depth[t] = 1 + max((d(x) for x in reqs(keys[t]) if x in keys), default=0)
        return depth[t]

    team = {t: json.loads(z.read(f"data/rctmod/trainers/{t}.json")) for t in keys}
    gym_depth = {n: d(ids[0]) for n, ids in gen_finds.STAGE_TRAINERS.items()}
    gym_depth[0] = 0
    out = {}
    for n in range(9):
        lo, hi = gym_depth[n], gym_depth[n + 1]
        seen, fights = set(), []
        for t in sorted((t for t in keys if lo < d(t) < hi), key=lambda t: (d(t), t)):
            name = team[t]["name"]
            if (name, d(t)) in seen:
                continue  # rival variants (by starter) share a name and a place in the series
            seen.add((name, d(t)))
            fights.append(f"{name} (Lv{max(p['level'] for p in team[t]['team'])})")
        out[n] = fights
    return out


# ---- book content ---------------------------------------------------------------------------------------------------

def lane_x(count):
    """Spread up to 4 quests between x=2.5 and x=6.5."""
    if count <= 1:
        return [4.5][:count]
    step = min(2.0, 4.0 / (count - 1))
    return [2.5 + i * step for i in range(count)]


def chapter(n, fights):
    """Quest dicts for stage n: key, icon, title, subtitle, desc, tasks, rewards, shape, size, x, y, deps, hide."""
    k = kit(n)
    quests = []

    def add(key, icon, title, sub, desc, tasks, rew, shape="circle", size=1.0, x=0.0, y=0.0, deps=(), hide=False):
        quests.append(dict(key=key, icon=icon, title=title, sub=sub, desc=desc, tasks=tasks, rewards=rew,
                           shape=shape, size=size, x=x, y=y, deps=list(deps), hide=hide))

    # Stage intro
    if n == 0:
        add("intro", "minecraft:campfire", "Welcome to Campfiremons", "Read me first", [
            "Progress is measured in &6stages&r: beat a gym leader to reach the next one.",
            "Each stage unlocks Pokémon you may catch (legendaries come in tiers), better Poké Balls, and power "
            "items that start turning up in structure chests for you.",
            "",
            "Your Pokémon can't level past your &elevel cap&r: the ace level of your next unbeaten key trainer.",
            "Your &eTrainer Card&r shows your cap and progress. Press &aL&r for the Campfiremons League tab.",
        ], [check_task("s0/intro")], rewards("s0/intro", 3, ("rctmod:trainer_card", 1), (k["ball"], 16),
                                             (k["potion"], 8)), "gear", 2.0)
    else:
        title = f"{BADGES[n]} Badge" if n < 9 else "Champion!"
        add("intro", "cobblemon:" + gen_finds.STAGE_ICONS[n - 1], title, f"Stage {n} reached", [
            gen_finds.STAGES[n][1].replace("Beat ", "You beat ", 1),
        ], [adv_task(f"s{n}/intro", f"campfiremons:stage/{n}")],
            rewards(f"s{n}/intro", 5, (k["ball"], 16), (k["potion"], 8), (k.get("revive"), 4)), "gear", 2.0)

    # Lane A (y=-3): new this stage = finds + the gimmick it makes usable
    lane_a = []
    for f in (f for f in gen_finds.FINDS if f["stage"] == n and f["once"]):
        lane_a.append((f"find_{f['id']}", f["item"], f"Find the {f['name']}", "Explore structure chests", [
            f"It now turns up (once) in {gen_finds.WHERE}.", "Chests are per player, so check every one you pass."],
                       [adv_task(f"s{n}/find_{f['id']}", f"campfiremons:found/{f['id']}")],
                       rewards(f"s{n}/find_{f['id']}", 3, (k["candy"], 3))))
    if n in GIMMICKS:
        action, icon, title, how = GIMMICKS[n]
        lane_a.append((action, icon, title, "Use it in battle", [how], [mon_task(f"s{n}/{action}", action, 1)],
                       rewards(f"s{n}/{action}", 4, (k["potion"], 4), (k["candy"], 2))))

    # Lane B (y=0): Pokémon goals
    lane_b = []
    for key, icon, title, sub, desc, action, amount, form, shiny in GOALS[n]:
        lane_b.append((key, icon, title, sub, [desc] if desc else [],
                       [mon_task(f"s{n}/{key}", action, amount, form, shiny)],
                       rewards(f"s{n}/{key}", 4, (k["ball"], 16) if action == "catch" else (k["candy"], 4))))

    # Lane C (y=3): road to the next gym = key fights + exploration hint
    lane_c = []
    if n < 9 and fights.get(n):
        nxt_leader = LEADERS[n + 1][0]
        lane_c.append(("road", "rctmod:trainer_card", f"Before {nxt_leader}", "Key fights", [
            "These key trainers stand between you and the next gym:",
            *[f"&e- {f}" for f in fights[n]],
            "", "Each one you beat raises your level cap. They spawn near you in their own biomes.",
        ], [check_task(f"s{n}/road")], rewards(f"s{n}/road", 3, (k["potion"], 6), (k["candy"], 3))))
    if n in HINTS:
        lane_c.append(("explore", "minecraft:compass", "Out Exploring", "A hint", [HINTS[n]],
                       [check_task(f"s{n}/explore")], rewards(f"s{n}/explore", 2, (k["candy"], 2))))

    for y, lane in ((-3.0, lane_a), (0.0, lane_b), (3.0, lane_c)):
        prev = "intro"
        for x, (key, icon, title, sub, desc, tasks, rew) in zip(lane_x(len(lane)), lane):
            add(key, icon, title, sub, desc, tasks, rew, x=x, y=y, deps=[prev])
            prev = key

    # Gym capstone: completes when the next stage is reached
    if n < 9:
        nk = kit(n + 1)
        leader, where = LEADERS[n + 1]
        how = (f"{leader} spawns in {where}." if n < 8
               else f"Beat the Elite Four (Agatha, Bruno, Lance, Lorelei), then find {leader} in {where}.")
        add("gym", "cobblemon:" + gen_finds.STAGE_ICONS[n], f"Beat {leader}" if n < 8 else "Become the Champion",
            f"Reach Stage {n + 1}", [
                how, "",
                "Gym leaders are RCT key trainers: they spawn near you in those biomes once you've beaten the key "
                "trainers before them. Gyms 1-4 will also live in the hub town.",
                "", "Your whole party must be at or under your level cap to battle.",
            ], [adv_task(f"s{n}/gym", f"campfiremons:stage/{n + 1}")],
            rewards(f"s{n}/gym", 10, (nk["ball"], 32), (nk["candy"], 6), ("cobblemon:rare_candy", 2 if n >= 3 else 0)),
            "hexagon", 2.0, x=9.0, deps=["intro"], hide=True)
    return quests


# ---- SNBT output ----------------------------------------------------------------------------------------------------

def snbt(v, indent=0):
    tab = "\t" * indent
    if isinstance(v, tuple) and v[0] == "long":
        return f"{v[1]}L"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v}d"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        if not v:
            return "[ ]"
        inner = "\n".join(f"{tab}\t{snbt(x, indent + 1)}" for x in v)
        return f"[\n{inner}\n{tab}]"
    if isinstance(v, dict):
        inner = "\n".join(f"{tab}\t{k}: {snbt(v[k], indent + 1)}" for k in sorted(v))
        return f"{{\n{inner}\n{tab}}}"
    raise TypeError(v)


def write(rel, obj):
    p = QUESTS / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(snbt(obj) + "\n")


def main():
    args = [a for a in sys.argv[1:] if a != "--force"]
    if (QUESTS / "data.snbt").exists() and "--force" not in sys.argv:
        sys.exit(f"{QUESTS} already has a quest book (edited in game?). Re-run with --force to overwrite it.")
    fights = key_fights(args[0] if args else sorted(glob.glob(DEFAULT_JAR))[-1])
    shutil.rmtree(QUESTS, ignore_errors=True)

    write("data.snbt", {
        "default_autoclaim_rewards": "disabled", "default_consume_items": False, "default_quest_disable_jei": False,
        "default_quest_shape": "circle", "default_reward_team": False, "detection_delay": 20, "disable_gui": False,
        "drop_book_on_death": False, "drop_loot_crates": False, "emergency_items_cooldown": 300,
        "fallback_locale": "", "grid_scale": 0.5, "hide_excluded_quests": False,
        "icon": {"id": "minecraft:campfire"}, "lock_message": "", "pause_game": False,
        "progression_mode": "flexible", "show_lock_icons": True, "verify_on_load": False, "version": 13,
    })
    write("chapter_groups.snbt", {"chapter_groups": []})
    write("lang/en_us/file.snbt", {"file.0000000000000001.title": "Campfiremons"})
    chapter_titles = {}
    for n in range(10):
        cid = qid("chapter", n)
        name = f"stage_{n}"
        chapter_titles[f"chapter.{cid}.title"] = "Campfire Start" if n == 0 else (
            f"Stage {n}: {BADGES[n]} Badge" if n < 9 else "Stage 9: Champion")
        quests, lang = [], {}
        for q in chapter(n, fights):
            this = qid(f"s{n}", q["key"])
            deps = [qid(f"s{n}", d) for d in q["deps"]]
            if n > 0 and q["key"] == "intro":
                deps.append(qid(f"s{n - 1}", "gym"))  # each chapter opens from the previous gym capstone
            quest = {"dependencies": deps, "icon": {"id": q["icon"]}, "id": this, "rewards": q["rewards"],
                     "shape": q["shape"], "size": q["size"], "tasks": q["tasks"], "x": q["x"], "y": q["y"]}
            if q["hide"]:
                quest["hide_dependency_lines"] = True
            quests.append(quest)
            lang[f"quest.{this}.title"] = q["title"]
            lang[f"quest.{this}.quest_subtitle"] = q["sub"]
            if q["desc"]:
                lang[f"quest.{this}.quest_desc"] = q["desc"]
        write(f"chapters/{name}.snbt", {
            "default_hide_dependency_lines": False, "default_quest_shape": "", "filename": name, "group": "",
            "icon": {"id": "cobblemon:" + (gen_finds.STAGE_ICONS[n - 1] if n else "poke_ball")}, "id": cid,
            "order_index": n, "quest_links": [], "quests": quests,
        })
        write(f"lang/en_us/chapters/{name}.snbt", lang)
    write("lang/en_us/chapter.snbt", chapter_titles)
    print(f"wrote 10 chapters to {QUESTS.relative_to(QUESTS.parents[2])}; key fights: "
          + ", ".join(f"S{n}:{len(f)}" for n, f in fights.items()))


if __name__ == "__main__":
    main()
