def qid(*parts):
    """Stable 16-hex FTB Quests id from a name (so --force regenerates the same ids)."""
    return hashlib.sha1("/".join(map(str, parts)).encode()).hexdigest()[:16].upper()


# ---- task / reward builders -------------------------------------------------------------------------------------

def adv_task(key, advancement):
    return {"advancement": advancement, "criterion": "", "id": qid(key, "task"), "type": "advancement"}


def check_task(key):
    return {"id": qid(key, "task"), "type": "checkmark"}


def mon_task(key, action, amount, form="", pokemon=""):
    return {
        "action": action, "amount": ("long", amount), "biome": "", "dimension": "", "form": form, "gender": "",
        "id": qid(key, "task"), "poke_ball_used": "", "pokemon": pokemon, "pokemon_type": "", "region": "",
        "shiny": False, "time_max": ("long", 24000), "time_min": ("long", 0),
        "type": "cobblemon_tasks:cobblemon_task",
    }


def items(key, *pairs):
    return [{"count": n, "id": qid(key, "reward", i), "item": {"count": 1, "id": item}, "type": "item"}
            for i, (item, n) in enumerate(pairs)]


def xp(key, levels):
    return [{"id": qid(key, "xp"), "type": "xp_levels", "xp_levels": levels}]


