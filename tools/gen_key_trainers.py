#!/usr/bin/env python3
"""The key fights between gyms turn up more often, and the quest book says where (DESIGN.md §3.1, "Key fights").

RCT spawns, for each player, a trainer picked by weight from those they may fight now. In the Radical Red series every
key trainer (the non-optional ones that raise the level cap) has spawnWeightFactor 0.25, a quarter of an ordinary
trainer's, and only spawns in a few biomes, so the one a player needed next could take hours to find. Only the
road between gyms changes: rivals (Terry, Brendan, May) and Team Rocket (Archer, Ariana, Giovanni), TYPES below. Gym
leaders, the Elite Four and the Champion stay as RCT ships them [decided 2026-11-22]. This writes:
- kubejs/data/rctmod/mobs/trainers/<single|groups>/<id>.json: RCT's own file for each of those with
  spawnWeightFactor set to KEY_WEIGHT. Only the next unbeaten key trainer can spawn for a player (the earlier ones are
  beaten once and for all, the later ones need it beaten), so this raises exactly the one they need.
  Modified copies of RCT's files, so they keep its licence: kubejs/data/rctmod/license.txt.
- kubejs/server_scripts/campfiremons/key_fights.js: those fights in series order, each with its variants (rival
  teams differ by starter), for key_fight_alerts.js, which tells a player in chat when one of theirs spawns.
- The "Before <leader>" quests in config/ftbquests/quests/lang/en_us.snbt: each of those fights gets the biomes it
  spawns in (RCT's biomeTagWhitelist, made readable), and the closing line says how spawning works.
Run it again after updating RCT (it rewrites both from the jar):
  python3 -I tools/gen_key_trainers.py <rctmod jar>
"""
import json
import os
import re
import sys
import zipfile

SERIES = 'radicalred'
KEY_WEIGHT = 0.375  # RCT's 0.25, half as much again
TYPES = {'rival', 'team_rocket'}
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'kubejs', 'data', 'rctmod')
LANG = os.path.join(ROOT, 'config', 'ftbquests', 'quests', 'lang', 'en_us.snbt')
FIGHTS_JS = os.path.join(ROOT, 'kubejs', 'server_scripts', 'campfiremons', 'key_fights.js')
MOBS = 'data/rctmod/mobs/trainers/'

# RCT's biome tag names (NeoForge's c: tags, plus vanilla's has_structure ones), as players would say them
BIOMES = {
    'is_underground': 'cave biomes underground', 'is_cave': 'caves', 'is_badlands': 'badlands',
    'is_wasteland': 'wastelands', 'is_savanna': 'savannas', 'is_plains': 'plains',
    'is_sparse_vegetation': 'sparse grassland', 'is_rare': 'rare biomes', 'has_structure/end_city': 'End cities',
    'is_nether': 'the Nether', 'is_wet': 'wet biomes', 'is_water': 'water', 'is_river': 'rivers',
    'is_beach': 'beaches', 'is_dense_vegetation': 'dense forest', 'is_lush': 'lush biomes',
    'is_spooky': 'spooky biomes', 'is_swamp': 'swamps', 'is_jungle': 'jungles', 'is_forest': 'forests',
    'is_hot': 'hot biomes', 'is_mountain': 'mountains', 'is_peak': 'peaks', 'is_plateau': 'plateaus',
    'is_hill': 'hills', 'is_cold': 'cold biomes',
}
CLOSING = ('Each one you beat raises your level cap. They come one at a time, in this order: only the next one you '
           "haven't beaten can appear, 25 to 70 blocks from you while you are in or near the biomes listed, and "
           'you get a chat message when one turns up.')

LICENSE = """The files under mobs/ are modified copies of Radical Cobblemon Trainers' trainer data
(https://gitlab.com/srcmc/rct/mod), Copyright (c) HDainester, used and shared under its licence
(the jar we ship declares GNU LGPL 3; the project's current licence is the Mod Community License, MCOML).
Changes: spawnWeightFactor of the non-optional Radical Red rivals and Team Rocket raised from 0.25 to %s; everything
else is as
RCT ships it. Generated by tools/gen_key_trainers.py; the change history is in this repository's git log.
""" % KEY_WEIGHT


def readable(tags):
    return ', '.join(BIOMES.get(t, t.replace('is_', '').replace('_', ' ')) for t in tags)


def main(jar):
    z = zipfile.ZipFile(jar)
    names = set(z.namelist())
    keys = {}
    for name in sorted(names):
        if not (name.startswith(MOBS) and name.endswith('.json')):
            continue
        mob = json.loads(z.read(name))
        if SERIES in mob.get('series', []) and not mob.get('optional', True) and mob.get('type') in TYPES:
            keys[name[len('data/rctmod/'):]] = mob
    by_name, ids = {}, {}
    for rel, mob in keys.items():
        tid = rel.rsplit('/', 1)[1][:-5]
        team = json.loads(z.read(f'data/rctmod/trainers/{tid}.json'))
        mob['spawnWeightFactor'] = KEY_WEIGHT
        path = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as f:
            f.write(json.dumps(mob, indent=2) + '\n')
        level = max(p['level'] for p in team['team'])
        tags = by_name.setdefault((team['name'], level), [])
        tags += [t for t in mob.get('biomeTagWhitelist', []) if t not in tags]
        ids.setdefault((level, team['name']), []).append(tid)
    with open(os.path.join(OUT, 'license.txt'), 'w') as f:
        f.write(LICENSE)
    print(f'{len(keys)} key trainers -> spawnWeightFactor {KEY_WEIGHT}')
    groups = [f"  {{ name: {json.dumps(name)}, level: {level}, ids: {json.dumps(sorted(v))} }}"
              for (level, name), v in sorted(ids.items())]
    with open(FIGHTS_JS, 'w') as f:
        f.write('// Generated by tools/gen_key_trainers.py from RCT\'s Radical Red series; don\'t edit by hand.\n'
                '// The key rival and Team Rocket fights in series order, each with its variants (rival teams by starter).\n'
                '// Server scripts share one scope (global can only be set from startup scripts), so this is a plain constant.\n'
                'const KEY_FIGHTS = [\n' + ',\n'.join(groups) + '\n]\n')
    print(f'{len(groups)} key fights -> {os.path.relpath(FIGHTS_JS, ROOT)}')

    # Quest book: "&e- Name (LvN)" lines in the key-fight quests get their biomes
    text = open(LANG).read()
    done = set()

    def line(m):
        name, level = m.group(1).replace('\\\\&', '&'), int(m.group(2))
        tags = by_name.get((name, level))
        if not tags:
            return m.group(0)  # a fight we leave alone (e.g. the Elite Four)
        done.add((name, level))
        return f'"&e- {m.group(1)} (Lv{level})&r: {readable(tags)}"'
    text = re.sub(r'"&e- (.+?) \(Lv(\d+)\)(?:&r: [^"]*)?"', line, text)
    text = re.sub(r'"Each one you beat raises your level cap\.[^"]*"', json.dumps(CLOSING), text)
    with open(LANG, 'w') as f:
        f.write(text)
    print(f'{len(done)} quest lines with biomes; closing line now: {text.count(CLOSING)}')


if __name__ == '__main__':
    main(sys.argv[1])
